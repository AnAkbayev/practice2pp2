# Booleans as Comparison Results
# Example 1: Equal values produce True.
print(10 == 10)

# Example 2: Different values produce False.
print(10 == 5)

# Example 3: Greater-than comparison.
age = 20
print(age > 18)

# Example 4: Less-than-or-equal comparison.
score = 75
print(score <= 100)

# Example 5: Compare two strings.
name = "Alice"
print(name == "Alice")
