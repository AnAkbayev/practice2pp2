# Boolean Values
# Example 1: A Boolean variable can be True or False.
is_student = True
print(is_student)

# Example 2: Store two Boolean values.
has_ticket = True
is_late = False
print(has_ticket)
print(is_late)

# Example 3: Check the type of a Boolean value.
value = True
print(type(value))

# Example 4: Boolean values can be used directly in conditions.
logged_in = True
if logged_in:
    print("Welcome!")

# Example 5: A Boolean can be changed.
active = True
active = False
print(active)
