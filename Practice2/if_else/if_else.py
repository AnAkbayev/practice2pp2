# If Else
# Example 1: Choose between two messages.
age = 16
if age >= 18:
    print("Adult")
else:
    print("Minor")

# Example 2: Check whether a number is positive or not.
number = -3
if number >= 0:
    print("Positive or zero")
else:
    print("Negative")

# Example 3: Check a password.
password = "python123"
if password == "python123":
    print("Correct password")
else:
    print("Wrong password")

# Example 4: Check a score.
score = 55
if score >= 60:
    print("Passed")
else:
    print("Failed")

# Example 5: Check whether a number is even.
number = 8
if number % 2 == 0:
    print("Even")
else:
    print("Odd")
