# If Statement
# Example 1: Run code when a condition is True.
age = 20
if age >= 18:
    print("You are an adult.")

# Example 2: Check a number.
number = 10
if number > 0:
    print("The number is positive.")

# Example 3: Check a string.
name = "Alice"
if name == "Alice":
    print("Hello, Alice!")

# Example 4: Check a temperature.
temperature = 30
if temperature > 25:
    print("It is warm.")

# Example 5: Use indentation to create the if block.
score = 90
if score >= 80:
    print("Good score!")
