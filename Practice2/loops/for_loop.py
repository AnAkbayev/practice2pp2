# For Loops
# Example 1: Loop through a list.
fruits = ["apple", "banana", "cherry"]
for fruit in fruits:
    print(fruit)

# Example 2: Loop through a string.
for letter in "Python":
    print(letter)

# Example 3: Use range() to count.
for number in range(5):
    print(number)

# Example 4: Use a start and stop value.
for number in range(2, 6):
    print(number)

# Example 5: Loop with a step.
for number in range(0, 11, 2):
    print(number)
