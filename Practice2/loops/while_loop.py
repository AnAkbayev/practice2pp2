# While Loops
# Example 1: Count from 1 to 5.
i = 1
while i <= 5:
    print(i)
    i += 1

# Example 2: Countdown.
number = 5
while number > 0:
    print(number)
    number -= 1

# Example 3: Print even numbers.
number = 2
while number <= 10:
    print(number)
    number += 2

# Example 4: Repeat a message.
count = 0
while count < 3:
    print("Hello!")
    count += 1

# Example 5: Build a simple total.
total = 0
number = 1
while number <= 5:
    total += number
    number += 1
print(total)
